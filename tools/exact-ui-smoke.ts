/** Exercise the production Contract with snapshots from real Git commands.
 * Web cannot spawn Git; only this test's data seam is replaced. */
import { execFile as exec } from 'node:child_process';
import { promisify } from 'node:util';
import { copyFileSync, mkdirSync, mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve, join } from 'node:path';
import { history, detail, filePatch, type Execute } from '../apps/exact-client/git';
const execute=promisify(exec), root=resolve(import.meta.dir,'..');
const repo=resolve(process.argv[2]??'/tmp/git-client-demo');
const run:Execute=async(program,args)=>(await execute(program.replace('path:',''),args,{maxBuffer:32*1024*1024})).stdout;
const h=await history(run,repo,1000);if(h.error||h.commits.length<3)throw new Error(h.error||'Use tools/make-fixture.py to create a multi-commit fixture first.');
const details:Record<string,Awaited<ReturnType<typeof detail>>>={},patches:Record<string,Awaited<ReturnType<typeof filePatch>>>={};
for(const c of h.commits.slice(0,12)){
  const d=await detail(run,repo,c.oid);if(d.error)throw new Error(d.error);details[c.oid]=d;
  for(const f of d.files)patches[c.oid+'|'+f.path]=await filePatch(run,repo,c.oid,f.path,f.oldPath);
}
const first=details[h.commits[0].oid],other=h.commits.slice(1,12).find(c=>details[c.oid].files.length&&details[c.oid].files[0].path!==first.files[0].path);
if(first.files.length<2||!other)throw new Error('Use the repository generated by tools/make-fixture.py.');
const source=join(root,'apps/exact-client');mkdirSync(join(source,'.exact'),{recursive:true});
const dir=mkdtempSync(join(source,'.exact/ui-smoke-'));
for(const f of ['app.contract','app.tamber','app.json','exact.mjs'])copyFileSync(join(source,f),join(dir,f));
writeFileSync(join(dir,'package.json'),JSON.stringify({name:'git-ui-smoke',private:true}));
writeFileSync(join(dir,'app.ts'),`import type {Answer,Sources} from './app.contract.d.ts';
export const appId='dev.runechat.git.exact';
export const grants='';
const page=${JSON.stringify(h)}, details=${JSON.stringify(details)}, patches=${JSON.stringify(patches)};
const blank={oid:'',author:'',email:'',date:'',parents:'',message:'',additions:0,deletions:0,initials:'',avatar:'#f2c6a0',files:[],error:''};
const sources:Sources={
 history:([repo,limit])=>repo?{...page,commits:page.commits.slice(0,limit),more:page.commits.length>limit}:{commits:[],head:'All branches',more:false,error:''},
 detail:([repo,oid])=>details[oid as keyof typeof details]??blank,
 filePatch:([repo,oid,path])=>patches[(oid+'|'+path) as keyof typeof patches]??{text:'',lines:[],pairs:[],error:''},
 pickRepository:()=>({path:${JSON.stringify(repo)},error:''})
};
export const answer:Answer=(source,args,store,storage,native)=>sources[source](args,store,storage,native);
`);
const second=first.files[1],next=details[other.oid];
writeFileSync(join(dir,'app.test.contract'),`test "graph workspace selects commits, files and older pages"
  size 1280x900
  tap "open"
  clock data
  expect tree has "history-pane"
  expect tree has "files-pane"
  expect tree has "diff-pane"
  expect text "file-path" == ${JSON.stringify(first.files[0].path)}
  tap "split"
  expect state split == true
  tap "unified"
  expect state split == false
  tap "file-1"
  clock data
  expect text "file-path" == ${JSON.stringify(second.path)}
  expect state patch.text == ${JSON.stringify(patches[first.oid+'|'+second.path].text)}
  tap "commit-${other.oid}"
  clock data
  expect text "file-path" == ${JSON.stringify(next.files[0].path)}
  tap "more"
  clock data
  expect text "count" == "${h.commits.length} commits"
`);
const env={...process.env,EXACT2:join(root,'.deps/exact'),EXACT_FEEDBACK:'0'};
console.log('Testing the production Contract against a real-Git snapshot (native process execution is tested separately).');
